def _place(rows: list, width: int, accent: list) -> list:
    """Centraliza a marca de acento na largura do glifo."""
    out = []
    for r in accent:
        pad = max(0, (width - len(r)) // 2)
        out.append(("." * pad + r + "." * width)[:width])
    return out


def glyph(ch: str) -> list:
    """11 linhas de largura variável ('#' = pixel aceso)."""
    if ch in CAPS:
        rows = CAPS[ch]
        w = len(rows[0])
        return ["." * w] * 2 + rows + ["." * w] * 2
    if ch in LOWER:
        rows = LOWER[ch]
        return ["." * len(rows[0])] * 2 + rows
    if ch in PUNCT:
        rows = PUNCT[ch]
        return ["." * len(rows[0])] * 2 + rows
    if ch in ACCENTED:
        base, acc = ACCENTED[ch]
        g = glyph(base)
        w = len(g[0])
        if ch.islower():
            if base == "i":                                  # í: acento no lugar do pingo, 2 px de largura
                return ["..", "..", ".#", "#.", "#.", "#.", "#.", "#.", "#.", "..", ".."]
            mark = _place(g, w, ACC[acc])
            return g[:2] + mark + g[4:]
        return _place(g, w, ACC[acc]) + g[2:]
    if ch in ("ç", "Ç"):
        g = glyph("c" if ch == "ç" else "C")
        w = len(g[0])
        return g[:9] + _place(g, w, ["..#.", ".#.."][:2])[:2] if ch == "Ç" else g[:9] + _place(g, w, [".#", "#."])
    raise KeyError(ch)


CHARSET = (list(CAPS) + list(LOWER) + list(PUNCT) + list(ACCENTED) + ["ç", "Ç"])


def text_width(text: str) -> int:
    return sum(len(glyph(c if c in CHARSET else "?")[0]) + 1 for c in text) - 1 if text else 0


def draw_text(cv: Canvas, x: int, y: int, text: str, color, shadow=None, scale: int = 1) -> int:
    """Desenha texto (y = topo da grade de 11 linhas). Retorna a largura. Sombra 1 px (baixo-direita) opcional."""
    cx = x
    for ch in text:
        g = glyph(ch if ch in CHARSET else "?")
        for gy, row in enumerate(g):
            for gx, v in enumerate(row):
                if v == "#":
                    for dy in range(scale):
                        for dx in range(scale):
                            if shadow:
                                cv.px(cx + gx * scale + dx + scale, y + gy * scale + dy + scale, shadow)
                    for dy in range(scale):
                        for dx in range(scale):
                            cv.px(cx + gx * scale + dx, y + gy * scale + dy, color)
        cx += (len(g[0]) + 1) * scale
    return cx - x - scale


def export(png: str, fnt: str, face: str = "LanderPixel") -> None:
    """Folha de glifos (brancos) + BMFont texto. Cada célula = largura do glifo × 11, linha de 16 glifos."""
    cells = [(c, glyph(c)) for c in CHARSET]
    per_row, cell_w = 16, 8
    rows_n = (len(cells) + per_row - 1) // per_row
    sheet = Canvas(per_row * cell_w, rows_n * (ROWS + 1))
    lines = [f'info face="{face}" size={ROWS} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 '
             f'padding=0,0,0,0 spacing=1,1',
             f"common lineHeight={ROWS + 2} base={BASE} scaleW={sheet.w} scaleH={sheet.h} pages=1 packed=0",
             f'page id=0 file="{png.split("/")[-1]}"', f"chars count={len(cells)}"]
    for i, (c, g) in enumerate(cells):
        ox, oy = (i % per_row) * cell_w, (i // per_row) * (ROWS + 1)
        w = len(g[0])
        for gy, row in enumerate(g):
            for gx, v in enumerate(row):
                if v == "#":
                    sheet.px(ox + gx, oy + gy, "white")
        lines.append(f"char id={ord(c)} x={ox} y={oy} width={w} height={ROWS} xoffset=0 yoffset=0 "
                     f"xadvance={w + 1} page=0 chnl=15")
    sheet.save(png, preview=False)
    with open(fnt, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
